/** Балды жолаққа айналдыру (UI үшін). */
export function scoreToBand(score: number): LevelBand {
  const s = Math.max(0, Math.min(10, Math.round(score)));
  if (s >= 9) return "9-10";
  if (s >= 7) return "7-8";
  if (s >= 5) return "5-6";
  if (s >= 3) return "3-4";
  if (s >= 1) return "1-2";
  return "0";
}

/** БМ топтары бойынша балдарды жинақтау. */
export function sumByBmGroup(
  rows: Array<{ criterion_code: string; ai_score: number; teacher_score: number | null }>,
  bm: "bm1" | "bm2" | "bm3",
  use: "ai" | "teacher" = "ai",
) {
  return rows.reduce((acc, row) => {
    const c = RUBRIC_BY_CODE[row.criterion_code];
    if (!c) return acc;
    const matches =
      bm === "bm2"
        ? c.bm === "bm2_analysis" || c.bm === "bm2_evidence"
        : c.bm === bm;
    if (!matches) return acc;
    const value =
      use === "teacher" ? (row.teacher_score ?? row.ai_score) : row.ai_score;
    return acc + (Number.isFinite(value) ? Number(value) : 0);
  }, 0);
}
