function buildRubricBlock() {
  return RUBRIC.map((c: RubricCriterion) => {
    const bands = (
      ["9-10", "7-8", "5-6", "3-4", "1-2", "0"] as const
    )
      .map((b) => `      ${b}: ${c.bandDescriptors[b]}`)
      .join("\n");
    return `▸ ${c.code} — ${c.name} (max=${c.maxScore})
  Сипаттама: ${c.description}
  Деңгей жолақтары:
${bands}`;
  }).join("\n\n");
}

